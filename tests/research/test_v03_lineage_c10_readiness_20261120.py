def test_forged_receipt_hash_fails_at_original_readiness_gate():
    item=audit_current(ROOT)
    matrix_file=ROOT/"scenarios/v1/release_matrix.json"
    matrix=json.loads(matrix_file.read_bytes())
    plan=json.loads((ROOT/"docs/v1/PLAN.json").read_bytes())
    rows=[
        json.loads((ART/"preparation"/(case["id"]+".prepare.json")).read_bytes())
        for case in matrix["cases"]
    ]
    bad=deepcopy(rows)
    bad[0]["native_binary_sha256"]="0"*64
    tested=assess_v03_readiness(
        plan,matrix,
        matrix_sha256=hashlib.sha256(matrix_file.read_bytes()).hexdigest(),
        preparation_receipts=bad,
        live_candidate_source_sha256=item["candidate_source_sha256"],
        live_native_binary_sha256=item["native_binary_sha256"],
    )
    assert tested["v03"]["calendar_preparation_verified"]==2
    assert tested["v03"]["completed_full_day_runs"]==0
    assert tested["case_preparation"][bad[0]["case"]]["status"]=="REJECTED_EVIDENCE"
